namespace ControlHome.Domain.Capabilities;

/// <summary>Canonical units. Connectors convert vendor values to these before reporting them.</summary>
public static class Units
{
    public const string Percent = "%";
    public const string Watt = "W";
    public const string WattHour = "Wh";
    public const string Celsius = "°C";
    public const string Kelvin = "K";
    public const string Degree = "°";
    public const string Minute = "min";
    public const string Millisecond = "ms";
    public const string MicrogramsPerCubicMeter = "µg/m³";
    public const string PartsPerMillion = "ppm";
    public const string PartsPerBillion = "ppb";
}
